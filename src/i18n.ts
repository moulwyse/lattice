export const MESSAGES: Record<Language, Messages> = { en, ru, uk, pl, de, es };

/** Word forms for "file" by Intl.PluralRules category; `other` is the fallback. */
export const FILE_WORDS: Record<Language, Partial<Record<Intl.LDMLPluralRule, string>> & { other: string }> = {
  en: { one: 'file', other: 'files' },
  ru: { one: 'файл', few: 'файла', many: 'файлов', other: 'файла' },
  uk: { one: 'файл', few: 'файли', many: 'файлів', other: 'файлу' },
  pl: { one: 'plik', few: 'pliki', many: 'plików', other: 'pliku' },
  de: { one: 'Datei', other: 'Dateien' },
  es: { one: 'archivo', other: 'archivos' },
};

export function fileCount(language: Language, count: number) {
  const words = FILE_WORDS[language];
  const category = new Intl.PluralRules(language).select(count);
  return `${count} ${words[category] ?? words.other}`;
}

/** Word forms for "session" by Intl.PluralRules category; `other` is the fallback. */
export const SESSION_WORDS: Record<Language, Partial<Record<Intl.LDMLPluralRule, string>> & { other: string }> = {
  en: { one: 'session', other: 'sessions' },
  ru: { one: 'сессия', few: 'сессии', many: 'сессий', other: 'сессии' },
  uk: { one: 'сесія', few: 'сесії', many: 'сесій', other: 'сесії' },
  pl: { one: 'sesja', few: 'sesje', many: 'sesji', other: 'sesji' },
  de: { one: 'Sitzung', other: 'Sitzungen' },
  es: { one: 'sesión', other: 'sesiones' },
};

export function sessionCount(language: Language, count: number) {
  const words = SESSION_WORDS[language];
  const category = new Intl.PluralRules(language).select(count);
  return `${count} ${words[category] ?? words.other}`;
}

export function translate(
  language: Language,
  key: MessageKey,
  values: Record<string, string | number> = {},
) {
  const template = MESSAGES[language][key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  );
}

/** Pick an interface language from a locale such as `ru-RU` or `uk_UA.UTF-8`. */
export function languageFromLocale(locale: string | undefined): Language | null {
  const code = locale?.toLowerCase().split(/[-_.]/)[0];
  return isLanguage(code) ? code : null;
}
